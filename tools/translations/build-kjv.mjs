/**
 * KJV (1769) from eBible.org USFM → data/translations/en-kjv.json.gz, plus the
 * KJV verse counts the versification code and the server use:
 * src/core/versification/kjv-counts.ts and data/meta/kjv-counts.json.
 *
 * Source (public domain; Crown patent in the UK):
 *   mkdir -p private/sources/ebible-eng-kjv
 *   curl -L -o private/sources/ebible-eng-kjv/eng-kjv_usfm.zip https://ebible.org/Scriptures/eng-kjv_usfm.zip
 *   unzip -o private/sources/ebible-eng-kjv/eng-kjv_usfm.zip -d private/sources/ebible-eng-kjv/x
 * Run:
 *   node tools/translations/build-kjv.mjs [private/sources/ebible-eng-kjv/x]
 *
 * Text: \add … \add* (the KJV's italics) → [ … ]; Strong's numbers, footnotes,
 * headings (Ps 119 letters) and pilcrows dropped; a Psalm title (\d) opens
 * verse 1, the verse it belongs to in canonical numbering.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bookMeta, books, clip, counts, dataDir, root, sourcesDir, writeTranslation } from './common.mjs';
import { normalizeSpace, readUsfmDir } from './usfm.mjs';
import { validateTranslation } from './validate.mjs';

const dir = process.argv[2] ?? join(sourcesDir, 'ebible-eng-kjv', 'x');
const usfm = readUsfmDir(dir);

const out = [];
for (const id of books.CANONICAL_BOOKS) {
  const book = usfm.get(id);
  if (!book) throw new Error(`KJV source has no ${id}`);
  const chapters = book.chapters.map((verses, c) => {
    const title = book.titles.get(c + 1);
    return verses.map((text, v) => normalizeSpace(`${v === 0 && title ? `${title} ` : ''}${text}`.replace(/¶/g, ' ')));
  });
  out.push({ id, ...bookMeta(id, 'en'), chapters });
}

const translation = {
  format: 'html-bible/translation',
  formatVersion: 1,
  id: 'en-kjv',
  linkName: 'KJV',
  version: '1.0.0',
  lang: 'en',
  name: 'King James Version',
  shortName: 'KJV',
  year: 1769,
  license: 'Public domain',
  source: 'https://ebible.org/Scriptures/eng-kjv_usfm.zip (eBible.org, King James Version 1769 with Strong’s numbers; public domain, Crown patent in the UK)',
  versification: 'kjv',
  books: out,
};

const errors = validateTranslation(translation);
const c = counts(translation);
const empty = out.flatMap((b) => b.chapters.flatMap((ch, ci) => ch.flatMap((t, vi) => (t ? [] : [`${b.id} ${ci + 1}:${vi + 1}`]))));
console.log(`KJV: ${c.books} books, ${c.chapters} chapters, ${c.verses} verses, empty: ${empty.length} ${empty.slice(0, 5).join(' ')}`);
if (c.books !== 66 || c.chapters !== 1189 || c.verses !== 31102) errors.push('expected 66 books, 1189 chapters, 31102 verses');
if (errors.length) {
  for (const e of errors.slice(0, 30)) console.log(`  ${e}`);
  process.exit(1);
}
writeTranslation(join(dataDir, 'translations', 'en-kjv.json.gz'), translation);

// Verse counts per chapter: the canonical scheme's shape.
const kjvCounts = Object.fromEntries(out.map((b) => [b.id, b.chapters.map((ch) => ch.length)]));
mkdirSync(join(dataDir, 'meta'), { recursive: true });
writeFileSync(join(dataDir, 'meta', 'kjv-counts.json'), `${JSON.stringify(kjvCounts)}\n`);
const lines = Object.entries(kjvCounts).map(([id, list]) => `  ${/^\d/.test(id) ? `'${id}'` : id}: [${list.join(', ')}],`);
writeFileSync(
  join(root, 'src', 'core', 'versification', 'kjv-counts.ts'),
  `/**
 * Verses per chapter in KJV numbering, the canonical scheme: the shape every
 * canonical key lives in. Generated by tools/translations/build-kjv.mjs from
 * the KJV text; do not edit by hand (data/meta/kjv-counts.json is the same
 * table for the server).
 */
import type { BookId } from '../books';

export const KJV_COUNTS: Record<BookId, number[]> = {
${lines.join('\n')}
};
`,
);
for (const [id, cc, vv] of [['GEN', 1, 1], ['PSA', 3, 1], ['JHN', 3, 16]]) console.log(`  ${id} ${cc}:${vv} ${clip(out.find((b) => b.id === id).chapters[cc - 1][vv - 1])}`);
